#!/bin/bash
# Generates src/api/apiDocs.cpp, which embeds the control API's documentation in the program, from the files in doc/.
# Run by the build before compiling. The output is only rewritten when it would change, so that an unchanged
# document does not trigger a rebuild.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/api/apiDocs.cpp"
delimiter="APIDOC"

embed()
{
	local name="$1" file="$2"

	if grep -q ")$delimiter\"" "$file"; then
		echo "gen_api_docs.sh: $file contains the raw string delimiter )$delimiter\"" >&2
		exit 1
	fi

	printf 'const char* const apiDocs::%s = R"%s(' "$name" "$delimiter"
	cat "$file"
	printf ')%s";\n\n' "$delimiter"
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
	echo "// Generated by build/gen_api_docs.sh from the files in doc/. Do not edit."
	echo
	echo '#include "apiDocs.hpp"'
	echo
	embed OPENAPI_SPEC "$root/doc/hiveApi.openapi.json"
	embed AGENT_GUIDE "$root/doc/hiveApiAgentGuide.md"
	embed HIVE_SCHEMA "$root/doc/hiveSchema.json"
} > "$tmp"

if ! cmp -s "$tmp" "$out"; then
	# Written through rather than copied, so the file gets the usual permissions rather than the temporary
	# file's private ones.
	cat "$tmp" > "$out"
	chmod g+w "$out" 2>/dev/null || true
	echo "Generated $out"
fi
